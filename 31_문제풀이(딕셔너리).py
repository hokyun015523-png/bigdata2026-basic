addr['김가현'] = '010-5555-1234'
addr['김혜현'] = '010-6666-1234'
print(addr)

# 키만 모은다 --> .keys()
print(list (addr.keys()))

search_name = input('찾는 친구 이름 입력하시오 : ')
# 딕셔너리의 키 부분에 찾는 친구 이름이 있는가(포함되어있나)
if search_name in addr.key():
    print(f'찾는 친구의 연락처는 {add[search_name]} 입니다')
else:
    print(f'{search_name}은 연락처가 없습니다.')

