# 빈 딕셔너리가 있을 때
addr = {} #addr = dict()

# 딕셔너리에 키와 값을 추가
# 딕셔너리 이름[키이름] = 값
addr['최재원'] = '010-1111-1234'
print(addr)

# 딕셔너리 값 수정(키가 이미 있어야 한다)
# 딕셔너리 이름[키이름] = 값
addr['최재원'] = '010-1111-5678'
print(addr) #--> 딕셔너리의 값이 수정

addr['최지윤'] = '010-2222-1234'
